import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';

import type { DetectInput, DetectionResult, Detector } from '../core/detect.js';

async function fileExists(p: string): Promise<boolean> {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

async function readJson(p: string): Promise<Record<string, unknown> | null> {
  try {
    const content = await readFile(p, 'utf8');
    return JSON.parse(content) as Record<string, unknown>;
  } catch {
    return null;
  }
}

/**
 * Detect a React Native project at `cwd`.
 *
 * RN projects have a `package.json` listing `react-native` in
 * dependencies (or devDependencies for some setups), plus per-platform
 * native subdirectories (`android/` and / or `ios/`) generated by the
 * RN CLI. We require both signals — `package.json` alone could be any
 * Node app, and platform subdirs alone could be a vanilla iOS+Android
 * monorepo without RN.
 *
 * Mutual exclusivity with the platform detectors: when this matches at
 * an RN root, the iOS detector and Android detector deliberately do NOT
 * match because they only consider their own root layouts (cwd-level
 * `.xcodeproj` / cwd-level `app/build.gradle*`). The wizard's install
 * dispatch picks the RN recipe, which in turn delegates to the platform
 * recipes with `cwd` overlaid to `<root>/android` and `<root>/ios`.
 */
export const reactNativeDetector: Detector = {
  kind: 'react-native',
  async detect({ cwd }: DetectInput): Promise<DetectionResult | null> {
    const pkg = await readJson(path.join(cwd, 'package.json'));
    if (!pkg) return null;
    const deps = {
      ...((pkg.dependencies as Record<string, unknown> | undefined) ?? {}),
      ...((pkg.devDependencies as Record<string, unknown> | undefined) ?? {}),
    };
    if (!('react-native' in deps)) return null;

    const hasAndroid = await fileExists(path.join(cwd, 'android'));
    const hasIos = await fileExists(path.join(cwd, 'ios'));
    if (!hasAndroid && !hasIos) return null;

    const evidence: Array<{ path: string; note?: string }> = [
      { path: 'package.json', note: 'react-native dependency' },
    ];
    if (hasAndroid) evidence.push({ path: 'android/', note: 'native module' });
    if (hasIos) evidence.push({ path: 'ios/', note: 'native module' });

    return { kind: 'react-native', confidence: 'high', evidence };
  },
};
